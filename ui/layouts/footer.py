"""
フッターレイアウトコンポーネント
"""

import streamlit as st

def show_footer():
    """
    フッター情報を表示
    """
    st.markdown("---")
    st.markdown("""
    ### 使い方
    1. サイドバーでGemini API Keyを入力
    2. 使用するモデルを選択（複数選択可）
    3. サンプル画像のカテゴリと画像を選択
    4. プロンプトをカスタマイズ（任意）
    5. 「オブジェクト検出を実行」ボタンをクリック

    ### 注意
    - このアプリはGemini APIを使用しています。有効なAPIキーが必要です。
    - 画像サイズが大きい場合は自動的にリサイズされます。
    - 検出結果はモデルによって異なる場合があります。
    - 複数モデルでの比較が可能です。
    """)
